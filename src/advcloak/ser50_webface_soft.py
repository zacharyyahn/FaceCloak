    @staticmethod
    def __dense(name, **kwargs):
        layer = nn.Linear(**kwargs)
        w = torch.from_numpy(_weights_dict[name]['weights'])
        
        # MXNet->PyTorch: transpose to match PyTorch (out_features, in_features)
        if w.shape != layer.weight.shape:
            if w.shape[::-1] == layer.weight.shape:
                w = w.T.contiguous()
            else:
                raise RuntimeError(f"[Dense] Unexpected weight shape for {name}: {w.shape} -> expected {layer.weight.shape}")
        
        layer.weight.data.copy_(w)
        
        if 'bias' in _weights_dict[name]:
            layer.bias.data.copy_(torch.from_numpy(_weights_dict[name]['bias']))
        
        return layer

    @staticmethod
    def __conv(dim, name, **kwargs):
        import torch
        import torch.nn as nn

        if   dim == 1:  layer = nn.Conv1d(**kwargs)
        elif dim == 2:  layer = nn.Conv2d(**kwargs)
        elif dim == 3:  layer = nn.Conv3d(**kwargs)
        else:           raise NotImplementedError()

        w = torch.from_numpy(_weights_dict[name]['weights'])
        expected = layer.state_dict()['weight'].shape  # (out, in, kh, kw) for Conv2d
        s = w.shape

        if s != expected:
            # Case A: (out, kh, kw, in) -> (out, in, kh, kw)
            if len(s) == 4 and s[0] == expected[0] and s[3] == expected[1]:
                w = w.permute(0, 3, 1, 2).contiguous()
            # Case B: (kh, kw, in, out) -> (out, in, kh, kw)
            elif len(s) == 4 and s[3] == expected[0] and s[2] == expected[1]:
                w = w.permute(3, 2, 0, 1).contiguous()
            # Case C: (in, out, kh, kw) -> (out, in, kh, kw)
            elif len(s) == 4 and s[0] == expected[1] and s[1] == expected[0]:
                w = w.permute(1, 0, 2, 3).contiguous()
            # Case D: 3D conv variants
            elif len(s) == 5 and s[-1] == expected[0] and s[-2] == expected[1]:
                w = w.permute(4, 3, 2, 0, 1).contiguous()
            elif len(s) == 5 and s[0] == expected[1] and s[1] == expected[0]:
                w = w.permute(1, 0, 2, 3, 4).contiguous()
            else:
                raise RuntimeError(f"[conv] Unexpected weight shape for {name}: {s} → expected {tuple(expected)}")

        # final copy
        layer.state_dict()['weight'].copy_(w)
        if 'bias' in _weights_dict[name]:
            layer.state_dict()['bias'].copy_(torch.from_numpy(_weights_dict[name]['bias']))

        return layer
    
    def to_device(self, device):
        self.to(device)
        # force any loose tensors created in custom loaders onto the same device
        for name, param in self.named_parameters(recurse=True):
            param.data = param.data.to(device)
        for name, buf in self.named_buffers(recurse=True):
            buf.data = buf.data.to(device)
        return self

    @staticmethod
    def __batch_normalization(dim, name, **kwargs):
        if   dim == 0 or dim == 1:  layer = nn.BatchNorm1d(**kwargs)
        elif dim == 2:  layer = nn.BatchNorm2d(**kwargs)
        elif dim == 3:  layer = nn.BatchNorm3d(**kwargs)
        else:           raise NotImplementedError()

        if 'scale' in _weights_dict[name]:
            layer.state_dict()['weight'].copy_(torch.from_numpy(_weights_dict[name]['scale']))
        else:
            layer.weight.data.fill_(1)

        if 'bias' in _weights_dict[name]:
            layer.state_dict()['bias'].copy_(torch.from_numpy(_weights_dict[name]['bias']))
        else:
            layer.bias.data.fill_(0)

        layer.state_dict()['running_mean'].copy_(torch.from_numpy(_weights_dict[name]['mean']))
        layer.state_dict()['running_var'].copy_(torch.from_numpy(_weights_dict[name]['var']))
        return layer

